async def ensure_database_exists(url: str):
    base_url, db_name = url.rsplit('/', 1)
    sys_url = base_url.replace("+asyncpg", "") + "/postgres"

    engine = create_engine(sys_url, isolation_level="AUTOCOMMIT")

    with engine.connect() as conn:
        # Проверяем, существует ли база
        result = conn.execute(text(f"SELECT 1 FROM pg_database WHERE datname='{db_name}'"))
        if not result.scalar():
            print(f"База данных '{db_name}' не найдена. Создаю...")
            conn.execute(text(f"CREATE DATABASE {db_name}"))
            print(f"База данных '{db_name}' успешно создана.")
        else:
            print(f"База данных '{db_name}' уже существует.")
    engine.dispose()


